CREATE PROCEDURE babel_convert_string_session_dateformat_p @s VARCHAR(30) AS
SELECT CONVERT(DATETIME, @s), CONVERT(DATE, @s)
GO

EXEC babel_convert_string_session_dateformat_p '28.09.2026'
