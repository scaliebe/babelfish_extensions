-- CONVERT of a character string to a date type follows SET DATEFORMAT
SET DATEFORMAT dmy
GO

SELECT CONVERT(DATETIME, '28.09.2026'), CONVERT(DATETIME, '30.12.1899'), CONVERT(DATETIME, '01.01.2034 00:00:00')
GO

SELECT CONVERT(SMALLDATETIME, '28.09.2026'), CONVERT(DATETIME2(0), '28.09.2026 13:14:15'), CONVERT(DATETIME, '28.09.2026 13:14:15')
GO

SELECT CONVERT(DATE, '28/09/2026'), CONVERT(DATE, '28-09-2026'), CONVERT(DATETIME, '1.2.2026'), CONVERT(DATETIMEOFFSET(0), '28.09.2026 10:00:00 +02:00')
GO

-- the same string is another date with another order
SELECT CONVERT(DATE, '01.02.2026'), CONVERT(DATETIME, '03/04/2026 10:20:30')
GO

-- an explicit style wins
SELECT CONVERT(DATETIME, '09/28/2026', 101), CONVERT(DATETIME, '28.09.2026', 104)
GO

-- formats that do not depend on the order
SELECT CONVERT(DATETIME, '20260928'), CONVERT(DATETIME, '2026-09-28T10:20:30'), CONVERT(DATE, '2026-09-28')
GO

SELECT TRY_CONVERT(DATETIME, '09.28.2026'), TRY_CONVERT(DATE, '28.09.2026')
GO

SELECT CONVERT(DATETIME, '09.28.2026')
GO

